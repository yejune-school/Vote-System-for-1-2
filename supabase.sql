drop function if exists public.get_vote_results();
create or replace function public.get_vote_results()
returns table(choice text,count bigint)
language sql
security definer
set search_path=public
as $$
  select choice,count(*)
  from public.votes
  group by choice
  order by case choice
    when '찬성' then 1
    when '반대' then 2
    when '기권' then 3
    else 4
  end;
$$;

