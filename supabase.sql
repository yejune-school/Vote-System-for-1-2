create table if not exists public.vote_settings (
  id bigint primary key,
  title text not null default '투표에 참여하세요.',
  description text default '찬성, 반대, 기권 중 하나를 선택해주세요.',
  updated_at timestamptz not null default now()
);

insert into public.vote_settings (id, title, description)
values (1, '투표에 참여하세요.', '찬성, 반대, 기권 중 하나를 선택해주세요.')
on conflict (id) do nothing;


create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  choice text not null,
  created_at timestamptz not null default now()
);

-- 기존 후보자 투표 구조를 사용하는 경우
alter table public.votes drop column if exists candidate_id;
alter table public.votes add column if not exists choice text;

-- 테스트/기존 투표 초기화
delete from public.votes;

-- 허용 값
alter table public.votes drop constraint if exists votes_choice_check;
alter table public.votes
  add constraint votes_choice_check
  check (choice in ('찬성','반대','기권'));

-- 1인 1표
alter table public.votes drop constraint if exists votes_user_id_key;
alter table public.votes
  add constraint votes_user_id_key unique (user_id);


-- RLS
alter table public.votes enable row level security;
alter table public.vote_settings enable row level security;

drop policy if exists "users can insert own vote" on public.votes;
drop policy if exists "users can view own vote" on public.votes;
drop policy if exists "users can read settings" on public.vote_settings;
drop policy if exists "authenticated can update settings" on public.vote_settings;

create policy "users can insert own vote"
on public.votes for insert to authenticated
with check (auth.uid() = user_id);

create policy "users can view own vote"
on public.votes for select to authenticated
using (auth.uid() = user_id);

create policy "users can read settings"
on public.vote_settings for select to anon, authenticated
using (true);

-- 관리자 설정 변경은 아래 ADMIN_EMAIL을 네 관리자 이메일로 바꿔서 사용하세요.
create policy "authenticated can update settings"
on public.vote_settings for update to authenticated
using ((auth.jwt() ->> 'email') = '여기에_관리자_Google_이메일')
with check ((auth.jwt() ->> 'email') = '여기에_관리자_Google_이메일');


-- 결과는 개인 user_id를 노출하지 않고 집계값만 반환
create or replace function public.get_vote_results()
returns table(choice text, vote_count bigint)
language sql
security definer
set search_path = public
as $$
  select v.choice, count(*)::bigint
  from public.votes v
  group by v.choice
  order by v.choice;
$$;

grant execute on function public.get_vote_results() to anon, authenticated;


-- 관리자만 투표 초기화
create or replace function public.reset_votes()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if (auth.jwt() ->> 'email') <> '여기에_관리자_Google_이메일' then
    raise exception '관리자만 투표를 초기화할 수 있습니다.';
  end if;

  delete from public.votes;
end;
$$;

grant execute on function public.reset_votes() to authenticated;


