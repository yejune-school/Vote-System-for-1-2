-- 기존 votes 테이블이 없으면 생성
CREATE TABLE IF NOT EXISTS public.votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    choice TEXT NOT NULL,

    created_at TIMESTAMPTZ
        NOT NULL DEFAULT NOW()
);


-- 기존 투표 초기화
DELETE FROM public.votes;


-- 혹시 기존 candidate_id가 있으면 삭제
ALTER TABLE public.votes
DROP COLUMN IF EXISTS candidate_id;


-- choice 제한
ALTER TABLE public.votes
DROP CONSTRAINT IF EXISTS votes_choice_check;

ALTER TABLE public.votes
ADD CONSTRAINT votes_choice_check
CHECK (
    choice IN ('찬성', '반대', '기권')
);


-- 1인 1표
DROP INDEX IF EXISTS votes_one_vote_per_user;

CREATE UNIQUE INDEX votes_one_vote_per_user
ON public.votes(user_id);


-- RLS
ALTER TABLE public.votes ENABLE ROW LEVEL SECURITY;


-- 기존 정책 삭제
DROP POLICY IF EXISTS "votes_select_own"
ON public.votes;

DROP POLICY IF EXISTS "votes_insert_own"
ON public.votes;


-- 본인 투표 조회
CREATE POLICY "votes_select_own"
ON public.votes
FOR SELECT
TO authenticated
USING (
    auth.uid() = user_id
);


-- 본인 이름으로만 투표 가능
CREATE POLICY "votes_insert_own"
ON public.votes
FOR INSERT
TO authenticated
WITH CHECK (
    auth.uid() = user_id
);


-- =====================================================
-- 투표 결과 함수
-- =====================================================

DROP FUNCTION IF EXISTS public.get_vote_results();

CREATE OR REPLACE FUNCTION public.get_vote_results()
RETURNS TABLE (
    choice TEXT,
    count BIGINT
)
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public
AS $$

    SELECT
        choice,
        COUNT(*) AS count

    FROM public.votes

    GROUP BY choice

    ORDER BY
        CASE choice
            WHEN '찬성' THEN 1
            WHEN '반대' THEN 2
            WHEN '기권' THEN 3
            ELSE 4
        END;

$$;


-- =====================================================
-- 관리자 투표 초기화
-- =====================================================

DROP FUNCTION IF EXISTS public.reset_votes();

CREATE OR REPLACE FUNCTION public.reset_votes()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$

BEGIN

    IF LOWER(auth.jwt() ->> 'email')
       <>
       LOWER('관리자이메일@example.com')
    THEN

        RAISE EXCEPTION
            '관리자만 투표를 초기화할 수 있습니다.';

    END IF;


    DELETE FROM public.votes;

END;

$$;


GRANT EXECUTE
ON FUNCTION public.get_vote_results()
TO authenticated;

GRANT EXECUTE
ON FUNCTION public.reset_votes()
TO authenticated;
