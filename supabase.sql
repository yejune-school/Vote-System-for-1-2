  '1-2 부반장 최지혁 탄핵 투표',
  '최지혁 학생의 1-2 부반장 탄핵에 대한 투표입니다.',
  true
)
on conflict(id) do nothing;

-- 기존 투표 초기화
delete from public.votes;

alter table public.votes drop column if exists candidate_id;

alter table public.votes drop constraint if exists votes_choice_check;
alter table public.votes add constraint votes_choice_check
check(choice in ('찬성','반대','기권'));

drop index if exists votes_one_vote_per_user;
create unique index votes_one_vote_per_user on public.votes(user_id);

alter table public.votes enable row level security;
alter table public.vote_settings enable row level security;

drop policy if exists "votes_select_own" on public.votes;
drop policy if exists "votes_insert_own" on public.votes;
drop policy if exists "settings_select" on public.vote_settings;
drop policy if exists "settings_update_admin" on public.vote_settings;

create policy "votes_select_own"
on public.votes for select to authenticated
using(auth.uid()=user_id);

create policy "votes_insert_own"
on public.votes for insert to authenticated
with check(auth.uid()=user_id);

create policy "settings_select"
on public.vote_settings for select to anon,authenticated
using(true);

